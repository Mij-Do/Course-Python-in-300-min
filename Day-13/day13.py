# ((==)) => هل يساوي 
# (> <) => اكبر من واصغر من 
# (>=  <=) => اكبر واصغر من اوي يساوي
# (!=) => لا يساوي

result1 = (10 == 10); # true
result2 = (10 == 11); # false

result3 = (10 > 10); # false
result4 = (10 < 10); # false 
result5 = (10 >= 10); # true 
result6 = (10 <= 10); # true 

result7 = (10 != 10); # false

print(result1);
print(result2);
print(result3);
print(result4);
print(result5);
print(result6);
print(result7);





